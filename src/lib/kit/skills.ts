/** Text ready for whole-word matching, with a sentence's last full stop let go ("React." → "react"). */
export function words(text: string): string {
	return normalize(text.replace(/\.(?=\s|$)/g, ' '));
}

/** The skills a text names, in list order, each once. */
export function skillsIn(text: string): string[] {
	const ready = words(text);
	return SKILLS.filter((skill) => ready.includes(` ${skill.toLowerCase()} `));
}
